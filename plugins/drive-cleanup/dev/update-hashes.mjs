#!/usr/bin/env node
// Records the SHA-256 of every script under ps/ in hooks/script-hashes.ts.
// The mod refuses to run a script whose hash does not match.
//
//   node dev/update-hashes.mjs          write the file
//   node dev/update-hashes.mjs --check  exit 1 if it is out of date

import { createHash } from 'node:crypto'
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, relative, sep } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const psRoot = join(root, 'ps')
const target = join(root, 'hooks', 'script-hashes.ts')

const files = []
const walk = dir => {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name)
    if (entry.isDirectory()) walk(full)
    else if (entry.name.endsWith('.ps1')) files.push(full)
  }
}
walk(psRoot)
files.sort()

const normalize = text => (text.startsWith('﻿') ? text.slice(1) : text).replace(/\r\n/g, '\n')
const lines = files.map(full => {
  const key = relative(psRoot, full).split(sep).join('/')
  const hash = createHash('sha256')
    .update(normalize(readFileSync(full, 'utf8')), 'utf8')
    .digest('hex')
  return `  '${key}': '${hash}',`
})

const text = `// Generated by dev/update-hashes.mjs: do not edit. The SHA-256 of each
// script under ps/ (BOM removed, LF line ends). A script whose hash does not
// match is never run.
export const SCRIPT_HASHES: Readonly<Record<string, string>> = {
${lines.join('\n')}
}
`

if (process.argv.includes('--check')) {
  let current = ''
  try {
    current = readFileSync(target, 'utf8')
  } catch {}
  if (current !== text) {
    console.error('hooks/script-hashes.ts is out of date: run node dev/update-hashes.mjs')
    process.exit(1)
  }
  console.log('Script hashes are up to date.')
} else {
  writeFileSync(target, text)
  console.log(`Recorded ${String(files.length)} script hashes.`)
}
